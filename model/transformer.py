class Transformer(nn.Module):
    """Standard Transformer with optional encoder and decoder stacks."""
    def __init__(
        self,
        d_model=512,
        nhead=8,
        num_encoder_layers=6,
        num_decoder_layers=6,
        dim_feedforward=2048,
        dropout=0.1,
        activation="relu",
        normalize_before=False,
        return_intermediate_dec=False,
    ):
        super().__init__()

        # Create encoder stack
        encoder_layer = TransformerEncoderLayer(
            d_model, nhead, dim_feedforward, dropout, activation, normalize_before
        )
        encoder_norm = nn.LayerNorm(d_model) if normalize_before else None
        self.encoder = TransformerEncoder(encoder_layer, num_encoder_layers, encoder_norm)

        # Create decoder stack
        decoder_layer = TransformerDecoderLayer(
            d_model, nhead, dim_feedforward, dropout, activation, normalize_before
        )
        decoder_norm = nn.LayerNorm(d_model)
        self.decoder = TransformerDecoder(
            decoder_layer,
            num_decoder_layers,
            decoder_norm,
            return_intermediate=return_intermediate_dec,
        )

        self._reset_parameters()

        self.d_model = d_model
        self.nhead = nhead

    def _reset_parameters(self):
        """Initialize parameters using Xavier uniform distribution."""
        for p in self.parameters():
            if p.dim() > 1:
                nn.init.xavier_uniform_(p)

    def forward(self, src, mask, query_embed, query_pos, value_pos):
        """Process source features through encoder-decoder architecture.
        
        Args:
            src: Source feature tensor
            mask: Optional attention mask
            query_embed: Query embeddings for decoder
            query_pos: Query position embeddings
            value_pos: Value position embeddings
            
        Returns:
            Decoder output (query refinement)
        """
        # Reshape and permute for transformer: (batch, channels, seq_len) -> (seq_len, batch, channels)
        bs, c, l = query_embed.shape
        query_embed = query_embed.permute(2, 0, 1)
        query_pos = query_pos.unsqueeze(0).expand(bs,-1,-1).permute(2, 0, 1)        
        value = src.flatten(2).permute(2, 0, 1)
        value_pos = value_pos.flatten(2).permute(2, 0, 1)
        
        # Flatten attention mask if provided
        if mask is not None:
            mask = mask.flatten(1)

        # Encode source features
        memory = self.encoder(value, src_key_padding_mask=mask, pos=value_pos)
        
        # Decode with encoder output
        hs = self.decoder(
            tgt=query_embed, memory=memory, memory_key_padding_mask=mask, pos=value_pos, query_pos=query_pos
        )
        
        # Reshape back to (batch, channels, seq_len)
        return hs.transpose(1, 2).transpose(0, 2)

